# Regenerate config/base_flare_targets.csv: the butt swell below 1.3 m per species and size,
# from the TapeS taper models (vonderach2023tapes, CRAN TapeS 0.14.1) at the height/DBH pairs of
# config/dbh_targets.csv. ratio = d(h) / d(1.3 m), forced to exactly 1 at 1.3 m so the flare never
# moves DBH. Run from the repo root:  conda run -n growpy Rscript config/base_flare_targets.R
suppressPackageStartupMessages(library(TapeS))
setTapeSoptions(Rfn = list(fn = "sig2"))

tapes_code <- c(norway_spruce = 1, silver_fir = 3, scots_pine = 5, douglas_fir = 8,
                european_beech = 15)
hx <- c(0, 0.1, 0.2, 0.3, 0.5, 0.7, 1.0, 1.3)

targets <- read.csv("config/dbh_targets.csv", comment.char = "#")
# Below 7 cm DBH TapeS leaves its range (h05 rows: beech not monotone, pine 2.4 x at the ground);
# the exporter clamps a smaller tree to the smallest row.
targets <- targets[targets$species %in% names(tapes_code) & targets$dbh_m >= 0.07, ]
rows <- list()
for (k in seq_len(nrow(targets))) {
  t <- targets[k, ]
  dbh_cm <- t$dbh_m * 100
  obj <- tprTrees(spp = tapes_code[[t$species]], Dm = list(dbh_cm), Hm = list(1.3),
                  Ht = t$height_m)
  d <- as.numeric(tprDiameter(obj, Hx = hx, cp = TRUE))
  ratio <- d / d[length(d)]
  stopifnot(all(is.finite(ratio)), all(diff(ratio) <= 1e-9), ratio[1] < 1.6)
  rows[[k]] <- data.frame(species = t$species, tapes_spp = tapes_code[[t$species]],
                          height_m = t$height_m, dbh_cm = round(dbh_cm, 2), h_m = hx,
                          ratio = round(ratio, 4))
}
out <- do.call(rbind, rows)
con <- file("config/base_flare_targets.csv", "w")
writeLines(c(
  "# Butt swell below 1.3 m: d(h_m) / DBH per species at the height/DBH pairs of dbh_targets.csv,",
  "# from TapeS taper models (vonderach2023tapes; TapeS 0.14.1, Rfn sig2). Generated by",
  "# config/base_flare_targets.R; do not edit by hand. Used by [unreal.growth_data_json] base_flare_species."
), con)
write.csv(out, con, row.names = FALSE, quote = FALSE)
close(con)
cat(sprintf("%d rows written\n", nrow(out)))
